def model_for(count: int = 2, edges: list[dict[str, str]] | None = None) -> dict[str, object]:
    tasks = [{"number": str(index + 1), "title": f"Task {index + 1}"} for index in range(count)]
    return {
        "schemaVersion": 2,
        "parserVersion": "2.0.0",
        "tasks": tasks,
        "edges": edges if edges is not None else ([{"from": "1", "to": "2"}] if count > 1 else []),
    }


