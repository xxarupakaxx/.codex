    def test_parallel_same_plan_serializes_generation_and_shares_cache(self) -> None:
        calls: list[int] = []
        calls_lock = threading.Lock()

        def fake(spec_path, run_dir, node_path, **_kwargs):
            with calls_lock:
                calls.append(1)
            time.sleep(0.05)
            raw = fake_svg()
            (run_dir / "raw.svg").write_bytes(raw)
            spec = json.loads(spec_path.read_text(encoding="utf-8"))
            receipt = fake_receipt(raw)
            receipt["nodeCount"] = len(spec["nodes"])
            receipt["edgeCount"] = len(spec["edges"])
            return receipt, raw

        def run():
            results: list[dict[str, object]] = []
            result_lock = threading.Lock()

            def generate():
                result = MODULE.archify_for_plan("parallel", model_for())
                with result_lock:
                    results.append(result)

            threads = [threading.Thread(target=generate) for _ in range(2)]
            for thread in threads:
                thread.start()
            for thread in threads:
                thread.join()
            self.assertEqual([item["status"] for item in results], ["verified", "verified"])
            self.assertEqual(len(calls), 1)

        self.invoke_with_fake(fake, run)

