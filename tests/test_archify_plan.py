    def test_layout_preserves_chain_independent_and_diamond_cardinality(self) -> None:
        chain_edges = [{"from": str(index), "to": str(index + 1)} for index in range(1, 20)]
        chain = MODULE._workflow_spec(MODULE.project_plan("chain", model_for(20, chain_edges)))
        self.assertEqual(len(chain["nodes"]), 20)
        self.assertEqual(len(chain["edges"]), 19)
        self.assertEqual(len(chain["lanes"]), 4)
        self.assertEqual([node["col"] for node in chain["nodes"][:6]], list(range(6)))

        independent = MODULE._workflow_spec(MODULE.project_plan("independent", model_for(20, [])))
        self.assertEqual(len(independent["lanes"]), 1)
        self.assertEqual(len(independent["edges"]), 0)
        self.assertEqual([node.get("yOffset") for node in independent["nodes"][:20:6]], [-96.0, -32.0, 32.0, 96.0])

        numbers = [str(index + 1) for index in range(20)]
        diamond_edges = [{"from": "1", "to": str(index)} for index in range(2, 8)]
        diamond_edges += [{"from": str(index), "to": str(index + 6)} for index in range(2, 8)]
        diamond_edges += [{"from": str(index), "to": str(index + 6)} for index in range(8, 14)]
        diamond_edges += [{"from": str(index), "to": "20"} for index in range(14, 20)]
        diamond_model = {"tasks": [{"number": number, "title": number} for number in numbers], "edges": diamond_edges}
        diamond = MODULE._workflow_spec(MODULE.project_plan("diamond", diamond_model))
        self.assertEqual(len(diamond["nodes"]), 20)
        self.assertEqual(len(diamond["edges"]), 24)
        self.assertEqual({node["type"] for node in diamond["nodes"]}, {"external"})

