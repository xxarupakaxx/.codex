    def test_progress_only_model_change_keeps_cached_svg_and_model_hash(self) -> None:
        calls: list[int] = []

        def fake(spec_path, run_dir, node_path, **_kwargs):
            calls.append(1)
            raw = fake_svg()
            (run_dir / "raw.svg").write_bytes(raw)
